    private static void subs(String scene, String... subs) {
        SUBS.put(scene, subs);
    }

    private static void rule(String scene, String sub, String... words) {
        for (String word : words) RULES.add(new Rule(scene, sub, word));
    }

    /** 某个大类下有哪些小类；收入 / 自定义大类返回空数组 */
    public static String[] subsFor(String scene) {
        String[] subs = SUBS.get(scene);
        return subs == null ? new String[0] : subs.clone();
    }

    public static boolean isSub(String scene, String sub) {
        if (scene == null || sub == null) return false;
        for (String s : subsFor(scene)) {
            if (s.equals(sub.trim())) return true;
        }
        return false;
    }

    /** 所有关键词规则，供 Classifier 做大类 + 小类一次判定 */
    public static List<Rule> rules() {
        return RULES;
    }

    /**
     * 猜小类：只在给定大类下面找，商品名优先，其次备注。
     * 认不出来返回 null，不硬塞。
     */
    public static String guess(String scene, String item, String note) {
        if (scene == null) return null;
        String hit = match(scene, item);
        if (hit != null) return hit;
        hit = match(scene, note);
        if (hit != null) return hit;
        String[] subs = subsFor(scene);
        // 只有一个小类的大类（比如「衣」）可以放心自动填
        return subs.length == 1 ? subs[0] : null;
    }

    /** 在指定大类下找最长命中的小类 */
    public static Rule find(String scene, String text) {
        if (scene == null || text == null) return null;
        String t = text.trim();
        if (t.isEmpty()) return null;
        Rule best = null;
        for (Rule r : RULES) {
            if (!r.scene.equals(scene)) continue;
            if (t.contains(r.word)
                    && (best == null || r.word.length() > best.word.length())) {
                best = r;
            }
        }
        return best;
    }

    private static String match(String scene, String text) {
        Rule r = find(scene, text);
        return r == null ? null : r.sub;
    }
